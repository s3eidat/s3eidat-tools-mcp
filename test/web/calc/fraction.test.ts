import { describe, expect, it } from 'vitest';
import tool, { approx, cmp, convergents, decimal, evaluate, mixedStr, parseDecimal, percent, R, shift, str } from '../../../src/tools/web/calc/fraction-calc.js';
import { fails, run } from './_run.js';

describe('calc_fraction (fraction-calc self-test)', () => {
  const E = (s: string) => str(evaluate(s).v);
  it('matches the website known answers', () => {
    expect(E('1/3 + 1/6')).toBe('1/2');
    expect(str(parseDecimal('0.(3)')!.v)).toBe('1/3');
    expect(E('0.(3)')).toBe('1/3');
    expect(str(parseDecimal('0.1(6)')!.v)).toBe('1/6');
    expect(str(parseDecimal('1.2(34)')!.v)).toBe('611/495');
    expect(str(parseDecimal('0.(9)')!.v)).toBe('1');
    expect(str(parseDecimal('-0.25')!.v)).toBe('-1/4');
    expect(E('1 1/2 + 3/4')).toBe('9/4');
    expect(mixedStr(evaluate('1 1/2 + 3/4').v)).toBe('2 1/4');
    expect(E('-1 1/2')).toBe('-3/2');
    expect([E('1/2 ÷ 3/4'), E('2/3 × 9/4'), E('3/4 - 5/6')]).toEqual(['2/3', '3/2', '-1/12']);
    expect([E('1/2 + 1/3 × 3'), E('(1/2 + 1/3) × 3'), E('(2/3)^2'), E('2^-2')]).toEqual(['3/2', '5/2', '4/9', '1/4']);
    let h = '0'; for (let i = 1; i <= 10; i++) h += ' + 1/' + i;
    expect(E(h)).toBe('7381/2520');
    const big = evaluate('1/3^40 + 1/3^40').v;
    expect([big.n, big.d]).toEqual([2n, 12157665459056928801n]);
    expect(decimal(R(1, 7)).text).toBe('0.(142857)');
    expect(decimal(R(1, 8)).text).toBe('0.125');
    expect(percent(R(1, 8))).toBe('12.5%');
    expect(decimal(R(1, 6)).text).toBe('0.1(6)');
    expect(decimal(R(-7, 3)).text).toBe('-2.(3)');
    expect(percent(R(2, 3))).toBe('66.(6)%');
    expect(approx(R(2, 3), 6)).toBe('0.666667');
    expect(approx(R(-1, 8), 2)).toBe('-0.13');
    expect(cmp(R(2, 3), R(3, 5))).toBe(1);
    expect(cmp(R(1, 2), R(2, 4))).toBe(0);
    const cv = convergents(parseDecimal('3.14159265')!.v, 1000n).map(str);
    expect(cv).toContain('22/7');
    expect(cv).toContain('355/113');
    expect(shift({ ip: '0', fp: '1', rp: '6' }, 2)).toBe('16.(6)');
    expect(shift({ ip: '0', fp: '1', rp: '6' }, 1)).toBe('1.(6)');
    for (const bad of ['1/0', '1 ÷ 0', '2 +', 'x', '(1']) expect(() => evaluate(bad)).toThrow();
  });
  it('runs as a tool in every mode', async () => {
    const c = await run(tool, { input: '1 1/2 + 3/4 × 2/5' });
    expect(c).toMatchObject({ fraction: '9/5', mixed: '1 4/5', decimal: '1.8', percent: '180%' });
    expect(c.steps[0]).toEqual({ text: 'Mixed number to improper fraction', math: '1 1/2 = 3/2 (1 × 2 + 1)' });
    const d = await run(tool, { mode: 'decimal_to_fraction', input: '3.14159265' });
    expect(d.approximations.map((x: { fraction: string }) => x.fraction)).toEqual(expect.arrayContaining(['22/7', '355/113']));
    const r = await run(tool, { mode: 'decimal_to_fraction', input: '0.1(6)' });
    expect(r.fraction).toBe('1/6');
    expect(r.steps.at(-1).math).toBe('x = 1/6');
    const f = await run(tool, { mode: 'fraction_to_decimal', input: '5/7' });
    expect([f.decimal, f.repeating, f.rounded]).toEqual(['0.(714285)', true, '0.714286']);
    const o = await run(tool, { mode: 'compare', input: '2/3, 3/5, 7/10' });
    expect(o.chain).toBe('3/5 < 2/3 < 7/10');
    expect(o.largest).toBe('7/10 (0.7)');
    const o2 = await run(tool, { mode: 'compare', input: '1 1/2; 3/2' });
    expect(o2.chain).toBe('3/2 = 3/2');
    await fails(tool, { input: '1/0' }, /denominator/);
  });
});
